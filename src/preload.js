const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('launcher', {
  getLibrary: () => ipcRenderer.invoke('library:get'),
  addGame: (game) => ipcRenderer.invoke('library:add', game),
  updateGame: (id, patch) => ipcRenderer.invoke('library:update', id, patch),
  removeGame: (id) => ipcRenderer.invoke('library:remove', id),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  launch: (id) => ipcRenderer.invoke('game:launch', id),
  stop: (id) => ipcRenderer.invoke('game:stop', id),
  openFolder: (id) => ipcRenderer.invoke('game:openFolder', id),
  pickGame: () => ipcRenderer.invoke('dialog:pickGame'),
  pickImage: () => ipcRenderer.invoke('dialog:pickImage'),
  fileIcon: (target) => ipcRenderer.invoke('game:icon', target),
  scan: () => ipcRenderer.invoke('scan:run'),
  pickForMe: (opts) => ipcRenderer.invoke('pick:game', opts),
  findArt: (id) => ipcRenderer.invoke('art:find', id),
  findMissingArt: () => ipcRenderer.invoke('art:findMissing'),
  artBroken: (id) => ipcRenderer.invoke('art:broken', id),
  artStatus: () => ipcRenderer.invoke('art:status'),
  windowControl: (action) => ipcRenderer.invoke('window:control', action),
  pathForFile: (file) => webUtils.getPathForFile(file),
  appInfo: () => ipcRenderer.invoke('app:info'),
  openDataFolder: () => ipcRenderer.invoke('data:openFolder'),
  exportData: () => ipcRenderer.invoke('data:export'),
  importData: () => ipcRenderer.invoke('data:import'),
  onChanged: (cb) => ipcRenderer.on('library:changed', () => cb()),
  sessions: () => ipcRenderer.invoke('library:sessions'),
  addCollection: (name) => ipcRenderer.invoke('collections:add', name),
  renameCollection: (from, to) => ipcRenderer.invoke('collections:rename', from, to),
  deleteCollection: (name) => ipcRenderer.invoke('collections:delete', name),
  createShortcut: (id) => ipcRenderer.invoke('game:shortcut', id),
  platform: () => ipcRenderer.invoke('app:platform'),
  onPickRequest: (cb) => ipcRenderer.on('ui:pick', () => cb()),
  onErrorToast: (cb) => ipcRenderer.on('toast:error', (_e, msg) => cb(msg)),
  updateStatus: () => ipcRenderer.invoke('update:get'),
  checkForUpdates: () => ipcRenderer.invoke('update:check'),
  downloadUpdate: () => ipcRenderer.invoke('update:download'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdateStatus: (cb) => ipcRenderer.on('update:status', (_e, s) => cb(s)),
  onArtProgress: (cb) => ipcRenderer.on('art:progress', (_e, n) => cb(n)),
  onAutoScan: (cb) => ipcRenderer.on('scan:auto', (_e, names) => cb(names)),
  onMaximized: (cb) => ipcRenderer.on('window:maximized', (_e, v) => cb(v)),
});
